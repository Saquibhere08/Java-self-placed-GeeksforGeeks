public class escapeSequence4 {
    public static void main(String[] args) {
        //Carriage Return
        System.out.println("Good Morning Geeks!\rHow are you all?");

        //Form Feed
        System.out.println("Good Morning Geeks!\fHow are you all?");

        //single qoute
        System.out.println("Good Morning 'Geeks!' How are you all?");

        //Double Quote
        System.out.println("Good Morning \"Geeks!\"How are you all?");

        //Backlash \
        System.out.println("\\- this is a backlash.");

        
    }
}
